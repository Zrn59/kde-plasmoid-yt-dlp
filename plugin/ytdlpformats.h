#pragma once

#include <QString>
#include <QStringList>

namespace YtdlpFormats {

enum class DownloadMode { VideoWithAudio = 0, VideoOnly = 1, AudioOnly = 2 };

enum class VideoQuality {
    UHD4K = 0,
    QHD = 1,
    FHD = 2,
    HD = 3,
    SD = 4,
    Low = 5,
    Lowest = 6,
    Best = 7,
    Worst = 8,
};

enum class VideoCodec { Any = 0, H264 = 1, H265 = 2, AV1 = 3, VP9 = 4, VP8 = 5 };
enum class VideoContainer { MP4 = 0, MKV = 1, WebM = 2, AVI = 3 };

enum class AudioQuality {
    Best = 0,
    High320 = 1,
    High256 = 2,
    Medium192 = 3,
    Medium128 = 4,
    Low96 = 5,
    Low64 = 6,
    Worst = 7,
};

enum class AudioCodec { Any = 0, AAC = 1, MP3 = 2, Opus = 3, Vorbis = 4, FLAC = 5 };

enum class SubtitleOption { None = 0, AutoGenerated = 1, Manual = 2, All = 3, Embed = 4 };
enum class SubtitleFormat { SRT = 0, VTT = 1, ASS = 2, LRC = 3 };
enum class SubtitleLanguage {
    Auto = 0,
    English = 1,
    Russian = 2,
    Spanish = 3,
    German = 4,
    French = 5,
    Japanese = 6,
    Korean = 7,
    Chinese = 8,
    All = 9,
};

enum class SpeedLimit { Unlimited = 0, Slow1M = 1, Medium5M = 2, Fast10M = 3, Custom50M = 4 };

struct DownloadOptions {
    QString url;
    QString outputDir;
    DownloadMode mode = DownloadMode::VideoWithAudio;
    VideoQuality videoQuality = VideoQuality::Best;
    VideoCodec videoCodec = VideoCodec::Any;
    VideoContainer videoContainer = VideoContainer::MP4;
    AudioQuality audioQuality = AudioQuality::Best;
    AudioCodec audioCodec = AudioCodec::Any;
    SubtitleOption subtitleOption = SubtitleOption::None;
    SubtitleLanguage subtitleLanguage = SubtitleLanguage::Auto;
    SubtitleFormat subtitleFormat = SubtitleFormat::SRT;
    SpeedLimit speedLimit = SpeedLimit::Unlimited;
    bool embedMetadata = true;
    bool embedThumbnail = true;
    bool allowPlaylist = false;
    bool previewMode = false;
    bool resumePartial = false;
    QString cookiesFile;
    bool useCookies = false;
    // 0 is a cookies file. 1.. are browser names from cookiesBrowserName().
    int cookiesBrowser = 0;
    QString customArgs;
    bool allowUnsafeArgs = false;
    QString downloadSections;
    QString outputTemplate;
    bool sponsorBlockRemove = false;
    QString previewWorkDir;
    QString tempDir;
};

QString runtimeRoot();
QString runtimeBinDir();
QString localYtdlpPath();
QString updateScriptPath();
QString findYtdlp();
QString findFfmpeg();
QString findMediaPlayer();
QString findDeno();
QString jsRuntimeSpec();
QString processPath();
QStringList buildArgs(const DownloadOptions &options, const QString &ffmpegPath);
QString normalizeDownloadSection(const QString &raw);
QStringList sanitizeCustomArgs(const QString &raw, bool allowUnsafe = false);
QString cookiesBrowserName(int id);
QString extractHttpUrl(const QString &text);
bool pathIsInside(const QString &path, const QString &directory);
QString finishedDownloadPath(const QString &line);

struct ParsedProgress {
    bool valid = false;
    double percent = 0;
    QString speed;
    QString eta;
};

ParsedProgress parseProgressLine(const QString &line);

// 1 when left is newer, -1 when right is newer, 0 when equal.
// A leading "v" and a suffix after "-" are ignored.
int compareVersions(const QString &left, const QString &right);

} // namespace YtdlpFormats
